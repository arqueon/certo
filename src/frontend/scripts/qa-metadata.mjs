import { chromium, expect } from '@playwright/test'
import { readFileSync, mkdirSync } from 'node:fs'
const fixture = JSON.parse(readFileSync(process.argv[2], 'utf8'))
const browser = await chromium.launch({ executablePath: process.env.QA_CHROMIUM || '/usr/bin/chromium', headless: true, args: ['--no-sandbox'] })
const artifacts = '/tmp/certo-0023-render'
mkdirSync(artifacts, { recursive: true })
const base = 'http://127.0.0.1:19300'
const url = `${base}/credentials/${encodeURIComponent(fixture.id)}`
let count = 0
const errors = []
async function check(fn) { await fn(); count++ }
async function session(owner = false, viewport = { width: 1360, height: 1000 }) {
  const ctx = await browser.newContext({ locale: 'es-MX', viewport })
  await ctx.route('**/*', route => new URL(route.request().url()).hostname === '127.0.0.1' || route.request().url().startsWith('data:') ? route.continue() : route.abort())
  if (owner) await ctx.addInitScript(({ user, token }) => { localStorage.setItem('token', token); localStorage.setItem('user', JSON.stringify(user)) }, fixture)
  const page = await ctx.newPage()
  page.on('pageerror', e => errors.push(e.message))
  return { ctx, page }
}
const visitor = await session()
await visitor.page.goto(url, { waitUntil: 'networkidle' })
await check(() => expect(visitor.page.locator('h1')).toHaveText('Análisis de datos'))
await check(() => expect(visitor.page.getByText('Persona de prueba', { exact: true })).toBeVisible())
await check(() => expect(visitor.page.locator('.institution')).toContainText('Universidad de Guadalajara'))
await check(() => expect(visitor.page.locator('.institution')).toContainText('UDG+'))
await check(() => expect(visitor.page.getByText('Periodo: 2026-B')).toBeVisible())
await check(() => expect(visitor.page.getByText('Nivel 6', { exact: true })).toBeVisible())
await check(() => expect(visitor.page.getByText('Español', { exact: true }).last()).toBeVisible())
await check(() => expect(visitor.page.locator('.criterion-results')).toContainText('Logrado'))
await check(() => expect(visitor.page.locator('.criterion-results')).not.toContainText('urn:qa:level'))
await check(() => expect(visitor.page.locator('.verification-seal')).not.toHaveAttribute('open'))
await check(() => expect(visitor.page.locator('.verification-seal summary')).toContainText('✓ Verificada'))
await check(() => expect(visitor.page.getByRole('heading', { name: 'Compartir y guardar' })).toHaveCount(0))
await check(() => expect(visitor.page.getByRole('button', { name: 'Guardar en mi wallet' })).toHaveCount(0))
await check(async () => expect(await visitor.page.locator('main.credential-page h2').allTextContents()).toEqual(['Qué acredita', 'Cómo se evaluó', 'Verificar']))
await visitor.page.screenshot({ path: `${artifacts}/public-desktop.png`, fullPage: true })
await visitor.page.locator('.verification-seal summary').click()
await check(() => expect(visitor.page.getByText('Firma del emisor: Correcta', { exact: false })).toBeVisible())
await visitor.page.screenshot({ path: `${artifacts}/checks-desktop.png`, fullPage: true })
await visitor.page.locator('.verification-seal summary').click()
await visitor.page.setViewportSize({ width: 390, height: 844 })
await check(async () => expect(await visitor.page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true))
await visitor.page.screenshot({ path: `${artifacts}/public-mobile.png`, fullPage: true })
const owner = await session(true)
await owner.page.goto(url, { waitUntil: 'networkidle' })
await check(() => expect(owner.page.getByRole('heading', { name: 'Compartir y guardar' })).toBeVisible())
await check(() => expect(owner.page.getByRole('button', { name: 'Guardar en mi wallet' })).toBeVisible())
await check(() => expect(owner.page.getByRole('link', { name: 'Añadir a LinkedIn' })).toBeVisible())
await check(async () => {
  const headings = await owner.page.locator('main.credential-page h2').allTextContents()
  expect(headings).toEqual(['Qué acredita', 'Cómo se evaluó', 'Verificar', 'Compartir y guardar'])
})
await owner.page.screenshot({ path: `${artifacts}/holder-desktop.png`, fullPage: true })
await owner.page.getByLabel('Mostrar mi nombre en la página pública').uncheck()
await owner.page.getByRole('button', { name: 'Guardar privacidad' }).click()
await owner.page.getByText('Privacidad guardada.', { exact: true }).waitFor()
await visitor.page.reload({ waitUntil: 'networkidle' })
await check(() => expect(visitor.page.getByText('Persona de prueba', { exact: true })).toHaveCount(0))
await check(() => expect(visitor.page.getByText('Periodo: 2026-B')).toBeVisible())
await visitor.page.screenshot({ path: `${artifacts}/hidden-mobile.png`, fullPage: true })
await owner.page.goto(`${url}/imprimir`, { waitUntil: 'networkidle' })
await check(() => expect(owner.page.locator('.holder-name')).toHaveText('Persona de prueba'))
await check(() => expect(owner.page.getByText('Nivel 6', { exact: true })).toBeVisible())
