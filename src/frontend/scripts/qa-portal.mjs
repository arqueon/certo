await issuer.page.goto(base)
await check(() => expect(issuer.page.locator('nav a[href="/issue"]')).toBeVisible())
await check(() => expect(errors).toEqual([]))
await browser.close()
console.log(`PORTAL_BROWSER_PASS ${count} assertions; artifacts: ${artifacts}`)
