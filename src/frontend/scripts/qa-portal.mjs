await owner.page.getByText('Privacidad guardada.', { exact: true }).waitFor()
await visitor.page.reload()
await check(() => expect(visitor.page.getByRole('heading', { name: 'Esta credencial no está disponible públicamente.' })).toBeVisible())
await visitor.page.goto(`${base}/verify`)
await visitor.page.getByRole('button', { name: 'Subir archivo', exact: true }).click()
await visitor.page.locator('input[type="file"]').setInputFiles(`${artifacts}/credential.json`)
