await check(() => expect(JSON.parse(readFileSync(`${artifacts}/history.json`, 'utf8')).type).toContain('ClrCredential'))
await owner.page.goto(`${base}${credentialPath}`)
await check(() => expect(owner.page.getByRole('button', { name: 'Descargar el archivo de la credencial' })).toBeVisible())
